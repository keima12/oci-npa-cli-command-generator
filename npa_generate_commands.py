#!/usr/bin/env python3
"""CSVからOCI Network Path Analyzer用のBashコマンドを生成する（実行はしない）。"""
import argparse
import csv
import ipaddress
import json
import shlex
import sys
from pathlib import Path

REQUIRED = {"source_ip", "destination_ip", "protocol", "destination_port"}


def ipv4(raw, line, name):
    try:
        return str(ipaddress.IPv4Address(raw))
    except ValueError as exc:
        raise ValueError(f"{line}行目: {name} はIPv4アドレスで指定してください: {raw!r}") from exc


def port(raw, line, name, required=False):
    if not raw:
        if required:
            raise ValueError(f"{line}行目: {name} が空です")
        return None
    if not raw.isdecimal() or not 1 <= int(raw) <= 65535:
        raise ValueError(f"{line}行目: {name} は1～65535の整数で指定してください: {raw!r}")
    return int(raw)


def endpoint(row, prefix, line):
    address = ipv4(row.get(prefix + "_ip", ""), line, prefix + "_ip")
    kind = (row.get(prefix + "_type", "") or "OCI").upper()
    subnet = row.get(prefix + "_subnet_id", "")
    if kind == "ON_PREM":
        if subnet:
            raise ValueError(f"{line}行目: {prefix}_type=ON_PREM にサブネットOCIDは指定できません")
        return {"type": "ON_PREM", "address": address}
    if kind != "OCI":
        raise ValueError(f"{line}行目: {prefix}_type は OCI または ON_PREM を指定してください")
    if subnet:
        if not subnet.startswith("ocid1.subnet."):
            raise ValueError(f"{line}行目: {prefix}_subnet_id がサブネットOCIDではありません")
        return {"type": "SUBNET", "address": address, "subnetId": subnet}
    return {"type": "IP_ADDRESS", "address": address}


def quote_json(value):
    return shlex.quote(json.dumps(value, ensure_ascii=False, separators=(",", ":")))


def make_command(row, line, args):
    source = endpoint(row, "source", line)
    destination = endpoint(row, "destination", line)
    protocol_name = row.get("protocol", "").upper()
    if protocol_name not in {"TCP", "UDP"}:
        raise ValueError(f"{line}行目: protocol はTCPかUDPを指定してください")
    dest_port = port(row.get("destination_port", ""), line, "destination_port", required=True)
    src_port = port(row.get("source_port", ""), line, "source_port")
    params = {"type": protocol_name, "destinationPort": dest_port}
    if src_port is not None:
        params["sourcePort"] = src_port

    parts = [
        "oci vn-monitoring path-analysis get-path-analysis-adhoc",
        "--compartment-id " + shlex.quote(args.compartment_id),
        "--source-endpoint " + quote_json(source),
        "--destination-endpoint " + quote_json(destination),
        "--protocol " + ("6" if protocol_name == "TCP" else "17"),
        "--protocol-parameters " + quote_json(params),
        '--query-options ' + quote_json({"isBiDirectionalAnalysis": True}),
    ]
    if args.region:
        parts.append("--region " + shlex.quote(args.region))
    if args.profile:
        parts.append("--profile " + shlex.quote(args.profile))
    return " \\\n  ".join(parts)


def main():
    parser = argparse.ArgumentParser(description="NPA用OCI CLIコマンドをCSVから生成（OCI APIは呼び出しません）")
    parser.add_argument("--input", required=True, type=Path, help="入力CSV")
    parser.add_argument("--output", default="npa_commands.sh", type=Path, help="出力Bashファイル")
    parser.add_argument("--compartment-id", required=True, help="分析を実行するコンパートメントOCID")
    parser.add_argument("--region", help="例: ap-osaka-1（省略時はOCI CLIの設定を使用）")
    parser.add_argument("--profile", help="OCI CLIプロファイル（省略可）")
    args = parser.parse_args()

    if not args.compartment_id.startswith("ocid1.compartment."):
        parser.error("--compartment-id にはコンパートメントOCIDを指定してください")
    try:
        with args.input.open("r", encoding="utf-8-sig", newline="") as stream:
            reader = csv.DictReader(stream)
            if reader.fieldnames is None:
                raise ValueError("CSVにヘッダーがありません")
            missing = REQUIRED - set(reader.fieldnames)
            if missing:
                raise ValueError("CSVの必須列がありません: " + ", ".join(sorted(missing)))
            commands = []
            for line, original in enumerate(reader, start=2):
                if None in original:
                    raise ValueError(f"{line}行目: 列数がヘッダーより多いです")
                row = {k: (v or "").strip() for k, v in original.items()}
                if not any(row.values()):
                    continue
                commands.append(make_command(row, line, args))
    except (ValueError, OSError) as exc:
        parser.exit(1, f"エラー: {exc}\n")

    if not commands:
        parser.exit(1, "エラー: CSVに試験データがありません\n")
    text = "#!/usr/bin/env bash\n# Generated by npa_generate_commands.py\n# コマンドの生成のみ。OCIへの送信はこのPythonでは行いません。\n\n"
    for num, cmd in enumerate(commands, start=1):
        text += f"# 試験 {num}\n{cmd}\n\n"
    try:
        args.output.write_text(text, encoding="utf-8", newline="\n")
    except OSError as exc:
        parser.exit(1, f"エラー: 出力できませんでした: {exc}\n")
    print(f"{len(commands)} 件のコマンドを生成しました: {args.output}")


if __name__ == "__main__":
    main()

